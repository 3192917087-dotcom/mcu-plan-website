import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import {normalizeReferenceSource,normalizeReferenceOcr,referenceTextAssessment} from '../reference-text.js';
import {parseReferenceOutline} from '../outline-policy.js';
import {readReferenceFiles,validateReferenceInterpretation,referenceReviewState,confirmReferenceInterpretation,mergeReferenceEvidence,referenceInterpretationEvidence} from '../reference-import.js';

const raw=await fs.readFile(new URL('./fixtures/reference-ocr-wps.txt',import.meta.url),'utf8');
const normalized=normalizeReferenceSource(raw).text;
const parsed=parseReferenceOutline(raw);
assert.deepEqual(parsed.chapters.map(c=>c.id),['1','2','3','4','5']);
assert.equal(parsed.chapters[0].title,'前言');
assert.equal(parsed.units.find(u=>u.number==='1.1').title,'研究背景');
assert.deepEqual(parsed.units.find(u=>u.number==='1.1').children,['1.1.1 国内研究现状','1.1.2 国外研究现状']);
assert.ok(parsed.units.find(u=>u.number==='1.3').children.includes('1.3.2 论文结构'));
assert.ok(parsed.units.find(u=>u.number==='3.1').children.includes('3.1.2 STM32 最小系统电路'));
assert.ok(parsed.units.find(u=>u.number==='2.4').children.some(s=>s.startsWith('2.4.1 ')));
assert.ok(normalized.includes('4.2 系统整体工作流程及初始化'));
assert.equal(normalizeReferenceSource(normalized).text,normalized,'清洗幂等，重复解读不能继续改变层级');
assert.ok(referenceTextAssessment(raw).issues.some(i=>i.line.includes('MAIRHREGI')));
assert.ok(referenceTextAssessment(raw).issues.some(i=>i.line.includes('异块')));
assert.equal(referenceReviewState({outlineText:parsed.rawText,warnings:[]},raw).status,'needs-review');
const adopted=confirmReferenceInterpretation(parsed.rawText);
assert.equal(adopted.status,'ready','有识别疑点的候选目录也允许不修改直接采用');
assert.equal(adopted.confirmedByUser,true);
assert.equal(adopted.outlineText,parsed.rawText,'采用时不擅自改写AI给出的目录');
assert.ok(adopted.warnings.length,'采用后保留识别疑点为非阻断提醒');
const clean='第一章 前言\n1.1 研究背景\n1.1.1 国内研究现状\n1.1.2 国外研究现状\n第二章 系统设计\n2.1 系统总体设计\n第三章 系统硬件设计\n3.1 模块选型\n3.2 PCB设计';
assert.equal(confirmReferenceInterpretation(clean).status,'ready');
assert.equal(referenceReviewState({outlineText:clean,warnings:[]},clean).status,'ready');
assert.ok(normalizeReferenceOcr('1.3 本设计的主要内容及论文结构 oeeeeeseeesoeeeeeeeseeee').endsWith('论文结构'));
assert.ok(normalizeReferenceOcr('2.1 配置Arduino').endsWith('Arduino'),'不得删除真实英文术语');
const evidence=referenceInterpretationEvidence('第五章 系统测试\n5.4 本章小结\n给出测试总结\n结论\n说明本论文的研究成果\n参考文献\n[1] 资料说明');
assert.ok(!evidence.writingDirections.some(d=>d.id==='5.4' && /研究成果|资料说明/.test(d.text)),'结论和文献不能绑到最后一个测试小节');
const introEvidence=referenceInterpretationEvidence('第一章 绪论\n本章将概述复杂系统维护决策的研究背景、研究意义、研究现状，并介绍本论文主要研究内容和基本结构。\n1.1 研究背景');
assert.ok(introEvidence.writingDirections[0].text.includes('论文结构安排'));
assert.ok(!introEvidence.writingDirections[0].text.includes('维护决策'),'通用第一章写作方向保留，旧例文对象不进入AI上下文');
assert.equal(referenceReviewState({outlineText:clean,warnings:[]},clean,{ocrReports:[{headingCount:5,label:'目录图',confidence:42}]}).status,'needs-review');
assert.throws(()=>confirmReferenceInterpretation(clean+'\n3.2 重复编号'),/重复/);
assert.equal(confirmReferenceInterpretation(clean.replace('PCB','【待核对】')).status,'ready');
assert.deepEqual(confirmReferenceInterpretation(clean,{warnings:['请核对原图','请核对原图']}).warnings,['请核对原图']);
assert.throws(()=>confirmReferenceInterpretation(''),/可用的章节目录/);
assert.throws(()=>confirmReferenceInterpretation('仅有背景说明，没有目录'),/可用的章节目录/);
assert.throws(()=>validateReferenceInterpretation({outlineText:clean.replace('2.1 系统总体设计','2.1 需求设计'),warnings:[]},clean),/改变第2章/);
assert.throws(()=>validateReferenceInterpretation({outlineText:clean+'\n3.3 新增硬件',warnings:[]},clean),/新增/);
assert.throws(()=>validateReferenceInterpretation({outlineText:clean+'\n第四章 测试',warnings:[]},clean),/新增/);
assert.equal(referenceTextAssessment('第二章 Firmware Architecture\n2.1 Raspberry Pi Configuration\n2.2 STM32CubeMX配置\n2.3 C++程序设计\n2.4 **模块设计').issues.length,0,'英文术语与星号占位不能误判乱码');
const many='第一章 绪论\n1.1 引言\n1.9 数据接口\n1.10 硬件功能\n1.11 软件功能\n1.12 系统测试\n11 章节十一\n11.1 功能验证\n12 章节十二\n12.1 结论';
const long=parseReferenceOutline(many);
assert.ok(long.units.some(u=>u.number==='1.12'));
assert.ok(long.chapters.some(c=>c.id==='11'));
assert.ok(long.chapters.some(c=>c.id==='12'));
assert.ok(parseReferenceOutline('第一章 绪论\n1.1 引言\n1.12 专项研究').units.some(u=>u.number==='1.12'),'局部清晰目录不能仅因1.1存在而把1.12擅自改为三级标题');
assert.ok(parseReferenceOutline('第一章 绪论\n1.1 引言\n1.1.1 研究背景\n1.12 专项研究').units.some(u=>u.number==='1.12'),'已有三级标题也不能成为修改真实二级编号的理由');
assert.equal(parseReferenceOutline('第五章 系统测试\n5 相相本丰刚这 11\n5.2 功能验证').chapters[0].title,'系统测试','OCR丢失5.1的小数点不能覆盖明确的第五章章名');
assert.equal(parseReferenceOutline('第三章 硬件设计\n3.1 主控电路\n3.2 采集电路\n第三章 硬件设计\n3.3 执行电路').units.length,3,'续页重复章名不能清空前页小节');
let passes=0;
const file={name:'模糊目录.png',size:1};
const result=await readReferenceFiles([file],{createWorker:async()=>({setParameters:async()=>{},recognize:async()=>({data:++passes===1?{text:raw,confidence:45}:{text:clean,confidence:90}}),terminate:async()=>{}})});
assert.equal(passes,2,'低质量图片要有一次不同版面模式复核');
assert.ok(result.ocrReports.length===1);
const word='第1章 绪论\n1.1 二级标题\n1.1.1 三级标题\n1.1.2 三级标题\n第三章 系统硬件设计\n3.1 主控模块微控制器的选择\n3.2 **模块设计\n可给出模块选型说明\n3.5 **PCB设计';
const reports=[{text:'1.1 研究背景\n1.1.1 国内研究现状\n1.1.2 国外研究现状\n1.2 研究目的\n3.1 主控模块徽控制器的选择\n3.5 =pos MAIRHREGI',confidence:70,headingCount:6}];
const merged=mergeReferenceEvidence(word,reports),mergedParsed=parseReferenceOutline(merged);
assert.equal(mergedParsed.units.find(u=>u.number==='1.1').title,'研究背景','具体截图标题补充Word的占位标题');
assert.ok(mergedParsed.units.find(u=>u.number==='1.2'),'截图新增小节保留');
assert.ok(merged.includes('3.1 主控模块微控制器的选择'),'Word清晰文字不被OCR乱码替换');
assert.ok(merged.includes('可给出模块选型说明'),'原Word写作方向保留');
assert.ok(!merged.includes('MAIRHREGI'));
assert.equal(referenceReviewState({outlineText:mergedParsed.rawText,warnings:[]},merged,{ocrReports:reports}).status,'ready');
const continuation=mergeReferenceEvidence('第三章 系统硬件设计\n3.1 硬件总体设计\n3.1.2 STM32最小系统电路设计',[{text:'3.12 STM32 最小系统电路\n第四章 系统软件设计\n4.1 软件工作流程',confidence:80,headingCount:3}]);
assert.equal(parseReferenceOutline(continuation).units.find(u=>u.number==='3.1').children[0],'3.1.2 STM32最小系统电路设计','续页缺父级也不能把OCR编号在合并后才恢复并覆盖清晰Word标题');
console.log(JSON.stringify({scenarios:11,status:'passed'}));
